#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Group {
    System,
    Scene,
    Object,
    Sculpt,
    Mask,
    Group,
    Topo,
    Layer,
    Paint,
    View,
    File,
    History,
}

#[derive(Debug, Clone, Copy, Serialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct Hints {
    pub read_only_hint: bool,
    pub destructive_hint: bool,
    pub idempotent_hint: bool,
    pub open_world_hint: bool,
}

pub struct Command {
    pub id: &'static str,
    pub mcp: &'static str,
    pub group: Group,
    pub label: &'static str,
    pub description: &'static str,
    pub keys: &'static [&'static str],
    pub hints: Hints,
    pub schema: fn() -> Value,
    pub run: fn(&mut Session, &Value) -> Result<Value, CommandError>,
}

#[derive(Debug, Default)]
pub struct Session {
    pub scene: Scene,
    pub history: History,
    pub stroke: Option<(fsc_core::ObjectId, fsc_sculpt::Stroke)>,
    pub loads: u64,
    /// Brush alphas loaded by name with alpha_load (the built-in ones are generated on demand).
    pub alphas: std::collections::HashMap<String, std::sync::Arc<fsc_sculpt::Alpha>>,
    /// Vector displacement maps captured by name with vdm_capture (the built-in ones are generated on demand).
    pub vdms: std::collections::HashMap<String, std::sync::Arc<fsc_sculpt::Vdm>>,
    /// Objects sent out through bridge_send: the object, the file, and the file's modification time when last seen.
    pub bridges: Vec<(fsc_core::ObjectId, String, std::time::SystemTime)>,
    /// The channel last copied with channel_copy.
    pub(crate) clipboard: Option<selection_cmds::Clip>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct CommandError {
    pub code: &'static str,
    pub message: String,
}

impl CommandError {
    pub fn new(code: &'static str, message: impl Into<String>) -> Self {
        Self { code, message: message.into() }
    }
}

pub(crate) fn no_args() -> Value {
    json!({"type": "object", "properties": {}, "required": [], "additionalProperties": false})
}

fn engine_info(_: &mut Session, _: &Value) -> Result<Value, CommandError> {
    Ok(json!({"engine": "formsculptor", "version": fsc_core::engine_version()}))
}

